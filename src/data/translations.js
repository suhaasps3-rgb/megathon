/** Fills `{name}` placeholders, e.g. fill(t.stepOf, { n: 1, total: 3 }). */
export function fill(template, vars = {}) {
  return String(template ?? '').replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}
